import { mkdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

const GENERATED_HEADER = '// Copyright (c) Suigar\n// SPDX-License-Identifier: Apache-2.0\n\n';
const GENERATED_DIR = join(import.meta.dirname, '../src/generated/presets');
const LOADERS_PATH = join(GENERATED_DIR, 'loaders.ts');
const CATALOGUES_PATH = join(GENERATED_DIR, 'catalogues.ts');
const PRESET_DIR = new URL('../src/animation/presets/', import.meta.url);
const GENERATOR_NOTICE = '// Generated by scripts/generate-preset-catalogues.ts.\n';

// Each deferred module exports a record of preset names and their animation sequences.
const catalogues = [{ path: 'battle-royale', exportName: 'BATTLE_ROYALE_PRESETS' }];

function isRecord(value: unknown): value is Record<string, unknown> {
	return value != null && typeof value === 'object';
}

async function readPresetNames(path: string, exportName: string): Promise<Array<string>> {
	const module: unknown = await import(new URL(path + '.ts', PRESET_DIR).href);
	const catalogue = isRecord(module) ? module[exportName] : undefined;
	if (!isRecord(catalogue)) {
		throw new Error(`Missing preset catalogue ${exportName} in ${path}`);
	}
	return Object.keys(catalogue);
}

const definitions = await Promise.all(
	catalogues.map(async ({ path, exportName }) => ({
		path: '../../animation/presets/' + path + '.js',
		exportName,
		names: await readPresetNames(path, exportName),
	})),
);
const registered = new Set(await readPresetNames('core', 'CORE_PRESET_SEQUENCES'));
for (const { names, path } of definitions) {
	for (const name of names) {
		if (registered.has(name)) {
			throw new Error(`Duplicate preset "${name}" in ${path}`);
		}
		registered.add(name);
	}
}

const loaders = definitions.map(
	({ path, exportName, names }) =>
		`{ names: ${JSON.stringify(names)}, load: () => import('${path}').then(module => module.${exportName}) }`,
);
const imports = definitions.map(
	({ path, exportName }) => `import { ${exportName} } from '${path}';`,
);
await mkdir(GENERATED_DIR, { recursive: true });
await Promise.all([
	writeFile(
		LOADERS_PATH,
		GENERATED_HEADER +
			GENERATOR_NOTICE +
			`export const PRESET_LOADERS = [\n${loaders.join(',\n')}\n];\n`,
	),
	writeFile(
		CATALOGUES_PATH,
		GENERATED_HEADER +
			GENERATOR_NOTICE +
			imports.join('\n') +
			'\nexport const DEFERRED_PRESETS = {\n' +
			definitions.map(({ exportName }) => `...${exportName},`).join('\n') +
			'\n};\n',
	),
]);
