import { writeFile } from 'node:fs/promises';

// Each deferred module exports a record of preset names and their animation sequences.
const catalogues = [{ path: 'battle-royale', exportName: 'BATTLE_ROYALE_PRESETS' }];
const presetDirectory = new URL('../src/animation/presets/', import.meta.url);
const outputDirectory = new URL('../src/generated/', import.meta.url);
const header = '// Generated by scripts/generate-preset-catalogues.ts.\n';
async function readPresetNames(path: string, exportName: string): Promise<Array<string>> {
	const module: unknown = await import(new URL(path + '.ts', presetDirectory).href);
	const catalogue: unknown = Object.getOwnPropertyDescriptor(module, exportName)?.value;
	if (catalogue == null || typeof catalogue !== 'object') {
		throw new Error(`Missing preset catalogue ${exportName} in ${path}`);
	}
	return Object.keys(catalogue);
}

const definitions = await Promise.all(
	catalogues.map(async ({ path, exportName }) => ({
		path: '../animation/presets/' + path + '.js',
		exportName,
		names: await readPresetNames(path, exportName),
	})),
);
const registered = new Set(await readPresetNames('core', 'CORE_PRESET_SEQUENCES'));
for (const { names, path } of definitions) {
	for (const name of names) {
		if (registered.has(name)) {
			throw new Error(`Duplicate preset "${name}" in ${path}`);
		}
		registered.add(name);
	}
}

const loaders = definitions.map(
	({ path, exportName, names }) =>
		`{ names: ${JSON.stringify(names)}, load: () => import('${path}').then(module => module.${exportName}) }`,
);
const imports = definitions.map(
	({ path, exportName }, index) => `import { ${exportName} as catalogue${index} } from '${path}';`,
);
await Promise.all([
	writeFile(
		new URL('preset-loaders.ts', outputDirectory),
		header + `export const PRESET_LOADERS = [\n${loaders.join(',\n')}\n];\n`,
	),
	writeFile(
		new URL('preset-catalogues.ts', outputDirectory),
		header +
			imports.join('\n') +
			'\nexport const DEFERRED_PRESETS = {\n' +
			definitions.map((_, index) => `...catalogue${index},`).join('\n') +
			'\n};\n',
	),
]);
